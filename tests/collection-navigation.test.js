"use strict";
const assert=require("node:assert/strict");
const vm=require("node:vm");
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const items=[1,2].map(id=>({libraryID:1,key:`ITEM000${id}`,version:1,isRegularItem:()=>true,getField:field=>({DOI:`10.1234/paper${id}`,title:`Example paper ${id}`,date:"2020"}[field]||""),getCreators:()=>[{creatorType:"author",lastName:"Example"}],getAttachments:()=>[],getCollections:()=>id===1?[1]:[1,2]}));
const collections=new Map([1,2,3].map(id=>[id,{id,libraryID:1,key:`COLL000${id}`,name:`Collection ${id}`,getChildItems:()=>id===1?items:id===2?[items[1]]:[]}]));
const scope=vm.createContext({Zotero:{Collections:{get:id=>collections.get(id)}},Services:{},URL,console});
for(const file of require("../src/module-map.js"))vm.runInContext(fs.readFileSync(path.join(root,file),"utf8"),scope,{filename:file});
(async()=>{
 const app=scope.LiteratureGraph;
 app._sessionRepository=await new scope.ZLGSessionStore.SessionRepository().init();
 const refs=items.map(scope.ZLGZoteroAdapter.itemToLocalRef);
 const index=scope.ZLGIdentity.createLocalIndex(refs);
 const works=refs.map((ref,i)=>({workKey:`openalex:W${i+1}`,provider:"openalex",externalId:`W${i+1}`,identifiers:{doi:ref.doi},title:ref.title,year:ref.year,authors:[],referencedExternalIds:[],localKeys:[scope.ZLGIdentity.localKey(ref)]}));
 app.createDiscoveryService=async snapshot=>{
  const service=new scope.ZLGDiscoveryService.DiscoveryService({localIndex:index,provider:{resolve(){throw new Error("Cached navigation must not request the provider");}}});
  if(snapshot)service.hydrate(snapshot);
  return service;
 };
 const original=scope.ZLGDiscoveryCore.createSession({sessionId:"session-old-collection",name:"Collection 1",rootSeedLocalKeys:refs.map(scope.ZLGIdentity.localKey),rootSeedWorkKeys:works.map(w=>w.workKey),activeSeedWorkKeys:["openalex:W2"],graphSnapshot:{works,edges:[]}});
 await app._sessionRepository.save(original);
 const first=await app.prepareCollectionContext(1);
 assert.equal(first.session.sessionId,original.sessionId,"exact legacy roots must recover the existing queue");
 assert.equal(JSON.stringify(first.session.activeSeedWorkKeys),'["openalex:W2"]');
 assert.equal(first.session.collectionScope.id,1);
 const second=await app.prepareCollectionContext(2,first.service.snapshot());
 assert.equal(second.session.rootSeedWorkKeys.length,1);
 assert.equal(second.session.rootSeedWorkKeys[0],"openalex:W2");
 assert.equal(second.session.activeSeedWorkKeys.length,0,"new scopes start with their own empty queue");
 second.session.activeSeedWorkKeys=["openalex:W2"];
 await app._sessionRepository.save(second.session);
 const back=await app.prepareCollectionContext(1,second.service.snapshot());
 assert.equal(back.session.sessionId,original.sessionId);
 assert.equal(JSON.stringify(back.session.activeSeedWorkKeys),'["openalex:W2"]');
 const again=await app.prepareCollectionContext(2,back.service.snapshot());
 assert.equal(again.session.sessionId,second.session.sessionId,"returning to a Collection must not create a duplicate exploration");
 assert.equal(JSON.stringify(again.session.activeSeedWorkKeys),'["openalex:W2"]');
 const empty=await app.prepareCollectionContext(3,again.service.snapshot());
 assert.equal(empty.session.rootSeedWorkKeys.length,0);
 assert.equal(empty.session.collectionScope.id,3);
 const count=app._sessionRepository.list().length;
 const recent=app._sessionRepository.recent().sessionId;
 const picker=await app.prepareCollectionContext(null);
 assert.equal(picker.chooseCollection,true);
 assert.equal(app._sessionRepository.list().length,count,"opening a chooser must not create an empty saved exploration");
 assert.equal(app._sessionRepository.recent().sessionId,recent);
 await assert.rejects(app.prepareCollectionContext(999),/已不存在/);
 console.log("collection-navigation.test.js: all assertions passed");
})().catch(error=>{console.error(error);process.exitCode=1;});
